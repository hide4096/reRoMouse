% =========================================================
%  逆システムフィードフォワード設計 (2次ローパス付)
% =========================================================
%clear; close all; clc;

% --- 対象プラント G(z)
b = 0.2890;
a = [1, -1.7768, 0.7798];
Gz = tf(b, a, 0.001); % Ts = 1 (任意のサンプリング周期)

% --- 2次ローパスフィルタ Q(z)
alpha = 0.9; % 平滑度 (0.8~0.95 推奨)
numQ = (1 - alpha)^2;
denQ = [1, -2*alpha, alpha^2];
Qz = tf(numQ, denQ, 0.001);

% --- 逆システム F(z) = G^-1(z) * Q(z)
Fz = inv(Gz) * Qz;

% --- プラント＋フィードフォワード応答（ステップ追従）
Tz = minreal(Gz * Fz); % 簡略化
figure;
step(Tz);
title('ステップ追従応答 (G(z) * F(z))');
grid on;

% --- 各伝達関数を確認
disp('--- G(z) ---');
Gz

disp('--- Q(z) ---');
Qz

disp('--- F(z) = G^-1(z)*Q(z) ---');
Fz

% --- 安定性チェック
figure;
pzmap(Fz);
title('F(z) の極・零配置');
grid on;
